'use client';

import { useEffect, useState } from 'react';
import api from '@/lib/api';
import { Button } from '@/components/ui/button';

export default function DeliveryPage() {
  const [reports, setReports] = useState([]);
  const [deliveries, setDeliveries] = useState([]);
  const [selected, setSelected] = useState(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState('');
  const [values, setValues] = useState([]);
  const [reviewed, setReviewed] = useState(false);

  async function load() {
    setLoading(true); setError('');
    try { setReports((await api.get('/ng/public-health/reports', { params: { limit: 100 } })).data.reports || []); }
    catch (failure) { setReports([]); setError(failure.response?.data?.error || 'Reports could not be loaded.'); }
    finally { setLoading(false); }
  }
  useEffect(() => { load(); }, []);

  async function inspect(report) {
    setBusy(true); setError(''); setSelected(null); setDeliveries([]); setValues([]); setReviewed(false);
    try {
      const [response, content] = await Promise.all([api.get(`/ng/public-health/reports/${report.id}/delivery`), api.get(`/ng/public-health/reports/${report.id}`)]);
      setDeliveries(response.data.deliveries || []); setValues(content.data.values || []); setSelected({ ...report, ...content.data.report });
    } catch (failure) { setError(failure.response?.data?.error || 'Delivery evidence could not be loaded.'); }
    finally { setBusy(false); }
  }
  async function act(action) {
    if (!selected || busy || !reviewed) return;
    const report = selected; setBusy(true); setError(''); setNotice('');
    try {
      if (action === 'approve') {
        await api.post(`/ng/public-health/reports/${report.id}/approve`, { notes: 'Independent review completed through CareOps.' });
        setNotice('Report approved. Delivery remains a separate action.');
      } else {
        const response = await api.post(`/ng/integrations/dhis2/sync/${report.id}`);
        setNotice(response.data.delivery?.status === 'confirmed' ? 'Delivery confirmed against remote DHIS2 values.' : 'Delivery requires reconciliation. Inspect the retained evidence.');
      }
      await load(); await inspect(report); setSelected(null);
    } catch (failure) { setError(failure.response?.data?.error || 'The action failed. Review the retained state before retrying.'); }
    finally { setBusy(false); }
  }

  return <main className="mx-auto max-w-6xl px-4 py-8 sm:px-6">
    <h1 className="text-3xl font-semibold">Reports and DHIS2 delivery</h1>
    <p className="mt-3 text-slate-600">Review approved aggregate reports and retained delivery evidence inside your assigned scope. A network response alone does not confirm delivery.</p>
    {error && <div role="alert" className="mt-4 rounded-lg border border-red-200 bg-red-50 p-4 text-red-900">{error}<Button className="ml-3" variant="outline" onClick={load} disabled={busy}>Reload reports</Button></div>}
    {notice && <p role="status" className="mt-4 rounded-lg bg-emerald-50 p-4 text-emerald-900">{notice}</p>}
    <section aria-label="Reports" className="mt-6 rounded-xl border bg-white p-5">
      {loading ? <p role="status">Loading authorised reports…</p> : !error && reports.length === 0 ? <p>No reports are available in your assigned scope.</p> : reports.map((report) => <div key={report.id} className="flex flex-wrap items-center justify-between gap-3 border-b py-4 last:border-0">
        <div><p className="font-semibold">{report.facility_name || 'Aggregate report'} · {report.report_period}</p><p className="text-sm text-slate-600">Status: {report.status}</p></div>
        <Button variant="outline" disabled={busy} onClick={() => inspect(report)}>Review delivery</Button>
      </div>)}
    </section>
    {selected && <section aria-label="Delivery evidence" className="mt-6 rounded-xl border bg-white p-5">
      <h2 className="text-xl font-semibold">{selected.report_period} · {selected.facility_name || 'Aggregate report'}</h2>
      <p className="mt-3 text-slate-600">Report status: {selected.status}. Generated by: {selected.generated_by_name || 'Recorded author'}.</p>
      <div className="mt-4 overflow-x-auto"><table className="w-full text-left"><caption className="sr-only">Report values for independent review</caption><thead><tr><th className="p-2">Indicator</th><th className="p-2">Programme</th><th className="p-2">Value</th></tr></thead><tbody>{values.map((value) => <tr key={value.id || value.indicator_id} className="border-t"><td className="p-2">{value.display_name || value.internal_key}</td><td className="p-2">{value.programme_area}</td><td className="p-2">{value.value === null || value.value === undefined ? 'Unavailable' : value.value}</td></tr>)}</tbody></table></div>
      {!values.length && <p>No report values. Delivery will remain blocked.</p>}
      {!deliveries.length ? <p className="mt-3">No retained delivery job. This report has not been submitted through the durable delivery service.</p> : deliveries.map((item) => <div key={item.id} className="mt-4 rounded-lg bg-slate-50 p-4"><p className="font-semibold">Delivery: {item.status}</p><p>Attempts: {item.attempts} · Result: {item.result?.code || 'Pending'}</p><p className="break-all text-sm text-slate-600">Receipt: {item.id}</p></div>)}
      <div className="mt-5 flex flex-wrap gap-3">
        {selected.permissions?.approve && <label className="flex w-full items-center gap-3"><input type="checkbox" checked={reviewed} onChange={(event) => setReviewed(event.target.checked)} />I reviewed these aggregate values and their reporting scope.</label>}
        {selected.permissions?.approve && ['draft','generated'].includes(selected.status) && <Button disabled={busy || !reviewed} onClick={() => act('approve')}>Approve after independent review</Button>}
        {selected.permissions?.approve && selected.permissions?.export && ['approved','sync_pending'].includes(selected.status) && <Button disabled={busy || !reviewed || !values.length} onClick={() => act('sync')}>{selected.status === 'sync_pending' ? 'Reconcile retained delivery' : 'Submit approved report'}</Button>}
      </div>
    </section>}
  </main>;
}
